/**
 * ReplayProviderDriver - a `ProviderDriver` that stands in for a built-in
 * driver and plays a recording instead of running the provider's CLI.
 *
 * It keeps the replaced driver's kind, metadata and settings schema, so the
 * legacy `settings.providers.<kind>` blob still decodes and clients render the
 * instance with that provider's name, icon and model picker. Each instance
 * reports a fixed ready, authenticated snapshot, answers text generation with
 * fixed strings, and spawns and probes nothing. Used by the web performance
 * harness through `replayDrivers.ts`.
 *
 * @module provider/replay/ReplayProviderDriver
 */
import {
  DEFAULT_MODEL,
  DEFAULT_MODEL_BY_PROVIDER,
  type ProviderDriverKind,
  type ServerProvider,
} from "@e6tools/contracts";
import { createModelCapabilities } from "@e6tools/shared/model";
import type { ProviderReplayRecording } from "@e6tools/shared/testing/providerReplay/recording";
import * as DateTime from "effect/DateTime";
import * as Effect from "effect/Effect";
import * as Stream from "effect/Stream";

import type * as TextGeneration from "../../textGeneration/TextGeneration.ts";
import { withInstanceIdentity } from "../Drivers/instanceIdentity.ts";
import { ProviderDriverError } from "../Errors.ts";
import {
  defaultProviderContinuationIdentity,
  type ProviderDriver,
  type ProviderInstance,
} from "../ProviderDriver.ts";
import { makeManualOnlyProviderMaintenanceCapabilities } from "../providerMaintenance.ts";
import { buildServerProvider } from "../providerSnapshot.ts";
import type { ServerProviderShape } from "../Services/ServerProvider.ts";
import {
  makeReplayProviderAdapter,
  type ReplayProviderAdapterOptions,
} from "./ReplayProviderAdapter.ts";
import { replayProfileFor } from "./replayProfiles.ts";

export type ReplayDriverOptions = Omit<ReplayProviderAdapterOptions, "recording">;

/** The model a replay instance offers when its recording does not name one; seeds bind threads to it. */
export const defaultReplayModelSlug = (kind: ProviderDriverKind): string =>
  DEFAULT_MODEL_BY_PROVIDER[kind] ?? DEFAULT_MODEL;

const REPLAY_BRANCH = "replay/recorded-change";

function titleFromMessage(message: string): string {
  const words = message
    .trim()
    .split(/\s+/)
    .filter((word) => word.length > 0);
  return words.length === 0 ? "Replay thread" : words.slice(0, 6).join(" ");
}

const replayTextGeneration: TextGeneration.TextGeneration["Service"] = {
  generateCommitMessage: (input) =>
    Effect.succeed({
      subject: "Apply recorded change",
      body: "Generated by the provider replay driver.",
      ...(input.includeBranch ? { branch: REPLAY_BRANCH } : {}),
    }),
  generatePrContent: () =>
    Effect.succeed({
      title: "Apply recorded change",
      body: "Generated by the provider replay driver.",
    }),
  generateBranchName: () => Effect.succeed({ branch: REPLAY_BRANCH }),
  generateThreadTitle: (input) => Effect.succeed({ title: titleFromMessage(input.message) }),
};

/** Wraps `driver` so its instances replay `recording` under the same kind and settings. */
export const makeReplayProviderDriver = <Config, R>(input: {
  readonly driver: ProviderDriver<Config, R>;
  readonly recording: ProviderReplayRecording;
  readonly options: ReplayDriverOptions;
}): ProviderDriver<Config> => {
  const { driver, recording, options } = input;
  const driverKind = driver.driverKind;
  const profile = replayProfileFor(driverKind);
  const modelSlug = recording.header.capturedWith?.model ?? defaultReplayModelSlug(driverKind);
  return {
    driverKind,
    metadata: driver.metadata,
    configSchema: driver.configSchema,
    defaultConfig: driver.defaultConfig,
    create: ({ instanceId, displayName, accentColor, enabled }) =>
      Effect.gen(function* () {
        const continuationIdentity = defaultProviderContinuationIdentity({
          driverKind,
          instanceId,
        });
        const checkedAt = DateTime.formatIso(yield* DateTime.now);
        const snapshotValue: ServerProvider = withInstanceIdentity({
          instanceId,
          driverKind,
          displayName,
          accentColor,
          continuationGroupKey: continuationIdentity.continuationKey,
        })(
          buildServerProvider({
            presentation: {
              displayName: driver.metadata.displayName,
              ...(profile.capabilities.supportsConversationRollback === false
                ? { supportsConversationRollback: false }
                : {}),
            },
            enabled,
            checkedAt,
            models: [
              {
                slug: modelSlug,
                name: modelSlug,
                isCustom: false,
                isDefault: true,
                capabilities: createModelCapabilities({ optionDescriptors: [] }),
              },
            ],
            probe: {
              installed: true,
              version: "replay",
              status: "ready",
              auth: { status: "authenticated" },
            },
          }),
        );
        const snapshot: ServerProviderShape = {
          resolveMaintenance: () =>
            Effect.succeed(
              makeManualOnlyProviderMaintenanceCapabilities({
                provider: driverKind,
                packageName: null,
              }),
            ),
          getSnapshot: Effect.succeed(snapshotValue),
          refresh: Effect.succeed(snapshotValue),
          streamChanges: Stream.never,
          applyUsageLimits: () => Effect.void,
        };
        // Runs in the instance scope the registry owns, so closing it stops playback.
        const adapter = yield* makeReplayProviderAdapter({ ...options, recording }).pipe(
          Effect.mapError(
            (cause) =>
              new ProviderDriverError({
                driver: driverKind,
                instanceId,
                detail: `Failed to start replay of '${recording.header.id}': ${cause.message}`,
                cause,
              }),
          ),
        );
        return {
          instanceId,
          driverKind,
          continuationIdentity,
          displayName,
          accentColor,
          enabled,
          snapshot,
          adapter,
          textGeneration: replayTextGeneration,
        } satisfies ProviderInstance;
      }),
  };
};

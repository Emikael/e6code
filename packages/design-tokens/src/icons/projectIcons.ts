/** The default project icon; `folder-code`, the name monograms use for older peers, maps here. */
export const PROJECT_ICON_DEFAULT: IconName = "folder";

const ICON_BY_LUCIDE_NAME = new Map<string, IconName>(
  PROJECT_ICONS.flatMap((entry) => entry.lucide.map((name) => [name, entry.icon] as const)),
);

/** The curated icon a stored Lucide name shows, or null when the caller should fall back. */
export function projectIconForLucideName(name: string): IconName | null {
  return ICON_BY_LUCIDE_NAME.get(name) ?? null;
}

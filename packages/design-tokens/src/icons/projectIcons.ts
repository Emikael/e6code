/**
 * Curated project icons (design direction 6.5) and the permanent map from the Lucide names
 * projects were saved with. A project stores `{ kind: "lucide", name }`; clients read the name
 * through this map at render time and never rewrite it, so older clients keep working.
 *
 * The domain is every name the picker could offer: all of lucide-react 0.564.0, the only
 * version E6 shipped. A name maps to the curated icon its user would recognise, or to null,
 * and the caller falls back to the project's favicon or the default icon. Changing what a
 * stored name shows bumps `PROJECT_ICON_MAP_VERSION`; the reviewed map is a test snapshot.
 *
 * Loaded lazily with the dynamic `<Icon name>` path; static UI never imports it.
 */
